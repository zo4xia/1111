/** 按编号取公告模板 */
export function getAnnouncement(no: string): AnnouncementTemplate | undefined {
  return ANNOUNCEMENT_TEMPLATES.find((a) => a.no === no);
}

/**
 * 渲染公告正文：代入阶段日期与届次。
 * 占位规则：正文用【选举日】【提名开始】等中文占位；未提供值的占位保留原样待填。
 */
export function renderAnnouncementBody(a: AnnouncementTemplate, fills: Record<string, string>): string {
  let { body } = a;
  Object.entries(fills).forEach(([k, v]) => {
    body = body.replaceAll(`【${k}】`, v);
  });
  return body;
}

/** 社区/居委会版称谓替换（甲方规则：村民→居民、村→社区、乡镇→街道） */
export function adaptOrgType(body: string, orgType: 'village' | 'community'): string {
  if (orgType !== 'community') return body;
  return body
    .replaceAll('村民委员会', '居民委员会')
    .replaceAll('村民', '居民')
    .replaceAll('村务监督委员会', '居务监督委员会')
    .replaceAll('村委会', '居委会')
    .replaceAll('本村', '本社区')
    .replaceAll('回村', '回社区')
    .replaceAll('全村', '全社区')
    .replaceAll('各村民小组', '各居民小组')
    .replaceAll('村民小组', '居民小组')
    .replaceAll('镇(街道)', '街道')
    .replaceAll('乡镇', '街道');
}

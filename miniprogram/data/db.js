function findElection(elId) { return DB.elections.find(e => e.el_id === elId) }
function orgElections(slug) { return DB.elections.filter(e => e.el_org_id === slug) }
function scopedOf(orgSlug, elId) {
  const f = (rows, key) => rows.filter(r => key.some(k => r[k] === orgSlug))
  return {
    stages: DB.election_stages.filter(s => s.es_election_id === elId),
    voters: f(DB.voters, ['vot_org_id']).filter(v => v.vot_election_id === elId),
    materials: f(DB.materials, ['mat_org_id']).filter(m => m.mat_election_id === elId),
    candidates: f(DB.candidates, ['cand_org_id']).filter(c => c.cand_election_id === elId),
    announcements: f(DB.announcements, ['ann_org_id']).filter(a => a.ann_election_id === elId),
    notifications: DB.notifications.filter(n => n.notif_org_id === orgSlug),
    results: f(DB.election_results, ['er_org_id']),
    roster: f(DB.roster, ['ros_org_id'])
  }
}

